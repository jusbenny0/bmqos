import { createHmac, scryptSync, timingSafeEqual } from "node:crypto";

// Authentication mode. Default = NO login (local / private network use): OS_AUTH unset and no OS_PASSWORD_HASH.
// OS_AUTH=password (or simply setting OS_PASSWORD_HASH) turns the password login on. OS_AUTH=none forces it off.
export const authOff = (): boolean =>
  process.env.OS_AUTH === "none" || (process.env.OS_AUTH !== "password" && !process.env.OS_PASSWORD_HASH);

export const COOKIE = "os_session";
export const sessionMaxAge = 60 * 60 * 24 * 14;

const secret = (): string => {
  const s = process.env.OS_SESSION_SECRET ?? "";
  if (s.length < 32) throw new Error("OS_SESSION_SECRET must be at least 32 chars");
  return s;
};
const sign = (payload: string): string => createHmac("sha256", secret()).update(payload).digest("base64url");
const user = (): string => process.env.OS_USER ?? "admin";

export const makeSession = (id: string): string => {
  const payload = Buffer.from(JSON.stringify({ u: user(), id, exp: Math.floor(Date.now() / 1000) + sessionMaxAge })).toString("base64url");
  return `${payload}.${sign(payload)}`;
};

// signature + validity (proxy, no DB); session id for the row check in the route (lib/sessions.ts)
export const sessionId = (token: string | undefined): string | null => {
  if (!token) return null;
  const [payload, sig] = token.split(".");
  if (!payload || !sig) return null;
  const want = Buffer.from(sign(payload)), got = Buffer.from(sig);
  if (want.length !== got.length || !timingSafeEqual(want, got)) return null;
  const data = JSON.parse(Buffer.from(payload, "base64url").toString()) as { u: string; id?: string; exp: number };
  return data.exp > Date.now() / 1000 && data.u === user() ? (data.id ?? "") : null;
};
export const isSession = (token: string | undefined): boolean => sessionId(token) !== null;

// hash: scrypt:<salt hex>:<hash hex> (generated by `npm run hash -- 'password'`)
export const checkPassword = (pw: string): boolean => {
  const [, salt, hash] = (process.env.OS_PASSWORD_HASH ?? "").split(":");
  if (!salt || !hash) return false;
  const got = scryptSync(pw, Buffer.from(salt, "hex"), 32), want = Buffer.from(hash, "hex");
  return got.length === want.length && timingSafeEqual(got, want);
};

